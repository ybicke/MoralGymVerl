"""Number macros + summary table for the seed-replicate PGG transfer.

Same cells and pooling as seed_figures.py (seed-grid / seed-multi):
one value per seed = pooled contribution rate of that cell, reported as
mean and min-max over seeds. Base and in-context (prompted) rows are
single cells.

  numbers_<prefix>.tex   \\<prefix>SR<Row>{Mean,Min,Max}   single round
                         \\<prefix>MR<Row><Opp>{Mean,Min,Max} multi round
  tables/seed_transfer.tex

  /usr/bin/python3.11 scripts/analysis/seed_numbers.py --model Qwen3-8B \\
      --step 200 --single-group ... --multi-group ... --out <dir>
"""
from __future__ import annotations

import argparse
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from seed_figures import load_cells, split  # noqa: E402

ROWS = [("Base", "Base"), ("Prompted", "Base + principle"),
        ("Grpo", "GRPO"), ("Sdpo", "SDPO")]


def pct(x: float) -> int:
    return int(Decimal(str(100 * x)).quantize(0, ROUND_HALF_UP))


def camel(s: str) -> str:
    return "".join(w.capitalize() for w in s.split("_"))


def rows(cells, step, principle, rate):
    """-> {row: [values]} with one value per seed (one for base rows)."""
    base, ctx, runs = split(cells, [step], principle)
    out = {"Base": [rate(base)], "Prompted": [rate(c) for c in ctx.values()]}
    for (channel, _), seeds in runs.items():
        out[channel.split()[0].capitalize()] = [rate(c) for c in
                                                sorted(seeds, key=lambda c: c.seed)]
    return out


def stats(vals):
    return pct(sum(vals) / len(vals)), pct(min(vals)), pct(max(vals))


def cell(vals) -> str:
    mean, lo, hi = stats(vals)
    return f"{mean}" if len(vals) == 1 else f"{mean} {{\\scriptsize ({lo}--{hi})}}"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model", required=True)
    ap.add_argument("--step", type=int, required=True)
    ap.add_argument("--principle", default="deontological")
    ap.add_argument("--single-group", action="append", required=True)
    ap.add_argument("--multi-group", action="append", required=True)
    ap.add_argument("--prefix", default="Seeds")
    ap.add_argument("--out", required=True, help="dir for generated/ files")
    a = ap.parse_args()

    single = rows(load_cells([Path(g) for g in a.single_group], "single_round", a.model),
                  a.step, a.principle, lambda c: c.first["cooperation_rate"])
    mcells = load_cells([Path(g) for g in a.multi_group], "multi_round", a.model)
    opps = list(next(iter(mcells)).blocks)
    multi = {o: rows(mcells, a.step, a.principle,
                     lambda c, o=o: c.blocks[o]["cooperation_rate"]) for o in opps}

    p = a.prefix
    macros = {f"{p}Step": str(a.step),
              f"{p}N": str(len(single["Sdpo"]))}
    for r, _ in ROWS:
        for name, vals in [(f"SR{r}", single[r])] + [
                (f"MR{r}{camel(o)}", multi[o][r]) for o in opps]:
            for k, v in zip(("Mean", "Min", "Max"), stats(vals)):
                macros[f"{p}{name}{k}"] = str(v)
    for r in ("Grpo", "Sdpo"):     # highest single-seed value over co-players
        macros[f"{p}MR{r}Max"] = str(max(stats(multi[o][r])[2] for o in opps))

    gen = Path(a.out) / "generated"
    (gen / "tables").mkdir(parents=True, exist_ok=True)
    lines = ["% generated by scripts/analysis/seed_numbers.py -- do not edit"]
    lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in sorted(macros.items())]
    (gen / f"numbers_{p}.tex").write_text("\n".join(lines) + "\n")

    n = len(single["Sdpo"])
    heads = " & ".join(o.replace("_", " ") for o in opps)
    tab = [
        "% generated by scripts/analysis/seed_numbers.py -- do not edit",
        r"\begin{table}[t]", r"\centering\small",
        rf"\begin{{tabular}}{{l c {'c' * len(opps)}}}", r"\toprule",
        rf" & Single round & \multicolumn{{{len(opps)}}}{{c}}{{Five rounds vs.}} \\",
        rf"\cmidrule(lr){{3-{2 + len(opps)}}}",
        rf" & & {heads} \\", r"\midrule",
    ]
    for r, label in ROWS:
        tab.append(f"{label} & {cell(single[r])} & "
                   + " & ".join(cell(multi[o][r]) for o in opps) + r" \\")
    tab += [r"\bottomrule", r"\end{tabular}",
            rf"\caption{{Contribution rate (\%) of {a.model} in the public-goods "
            rf"game after {a.step} training steps, without the principle in the "
            rf"prompt except for the base + principle row. Trained rows give the "
            rf"mean and, in brackets, the range over {n} seeds.}}",
            r"\label{tab:seed-transfer}", r"\end{table}"]
    (gen / "tables" / "seed_transfer.tex").write_text("\n".join(tab) + "\n")
    print(f"wrote {gen}/numbers_{p}.tex ({len(macros)} macros), "
          f"{gen}/tables/seed_transfer.tex")


if __name__ == "__main__":
    main()
