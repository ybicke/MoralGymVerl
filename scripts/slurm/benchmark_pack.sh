#!/bin/bash
#SBATCH --job-name=bench-pack
#SBATCH --partition=normal
#SBATCH --output=/dev/null
#SBATCH --error=/dev/null
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=4
#SBATCH --gpus-per-node=4
#SBATCH -C thp_never&nvidia_vboost_enabled
#SBATCH --time=03:00:00

# Packed benchmark launcher: up to 4 checkpoints on one node, one per GPU,
# each running its family's lm-eval benchmarks in sequence. Same mechanism
# as eval_pack.sh (--overlap steps, CUDA_VISIBLE_DEVICES per cell, batch
# payload with resolved run-dir names).
#
# Usage (normally via scripts/slurm/submit_benchmarks.py):
#   sbatch scripts/slurm/benchmark_pack.sh <batch.json>

set -uo pipefail

export PROJECT_ROOT="${SLURM_SUBMIT_DIR}"
if [ ! -f "${PROJECT_ROOT}/pyproject.toml" ]; then
    echo "ERROR: sbatch must be run from the MoralGymVerl repo root." >&2
    exit 1
fi
. "${PROJECT_ROOT}/scripts/slurm/cluster_env.sh" "${PROJECT_ROOT}"
export STORE_BASE="${MORALGYM_STORE_ROOT:-}"

BATCH_JSON="${1:?Usage: benchmark_pack.sh <batch.json>}"

LOG_BASE="${HOME}/logs_verl/eval"
mkdir -p "${LOG_BASE}"
GROUP_DIR="$(dirname "$(dirname "${BATCH_JSON}")")"
LOG_TAG="$(basename "$(dirname "$(dirname "${GROUP_DIR}")")")__$(basename "$(dirname "${GROUP_DIR}")")__$(basename "${GROUP_DIR}")"
exec > "${LOG_BASE}/benchmark_pack_${SLURM_JOB_ID}_${LOG_TAG}.out" 2>&1

WORKDIR="${LOG_BASE}/bench_${SLURM_JOB_ID}"
mkdir -p "${WORKDIR}"

echo "============================================="
echo "Packed benchmark batch"
echo "Job ID:   ${SLURM_JOB_ID}"
echo "Node:     ${SLURM_NODELIST}"
echo "Batch:    ${BATCH_JSON}"
echo "Started:  $(date)"
echo "============================================="
nvidia-smi --query-gpu=index,name,driver_version --format=csv

# One self-contained script per cell; cat ${WORKDIR}/cell_N.sh shows what ran.
PYTHONPATH="${PROJECT_ROOT}/src" /usr/bin/python3.11 - "${BATCH_JSON}" "${WORKDIR}" "${PROJECT_ROOT}" <<'PYEOF'
import json, os, shlex, sys
from moralgym_verl.eval.benchmarks import (
    load_harness, lm_eval_command, resolve_checkpoint)
batch_path, workdir, root = sys.argv[1:4]
ckpt_root = (os.environ.get("MORALGYM_CKPT_ROOT")
             or os.path.join(os.environ.get("SCRATCH", "/tmp"), "moralgym_verl_runs"))
cells = json.load(open(batch_path))["cells"]

for i, c in enumerate(cells):
    harness = load_harness(f"{root}/{c['config']}")
    kind, path = resolve_checkpoint(c["checkpoint"], ckpt_root)
    run_dir = (f"{root}/eval_results/{c['results_dir']}/{c['eval_group']}"
               f"/cells/{c['run_dir_stem']}_$SLURM_JOB_ID")
    meta = {"checkpoint": c["checkpoint"], "checkpoint_kind": kind,
            "checkpoint_path": path, "base_model": harness["model_name"],
            "config": c["config"], "benchmarks": c["benchmarks"]}
    lines = [
        "#!/bin/bash",
        "# Generated by benchmark_pack.sh: one checkpoint, benchmarks in sequence.",
        "set -uo pipefail",
        f"export CUDA_VISIBLE_DEVICES={i}",
        f'RUN_DIR="{run_dir}"',
        'mkdir -p "${RUN_DIR}"',
        f"cat > \"${{RUN_DIR}}/cell.json\" <<'JSON'\n{json.dumps(meta, indent=2)}\nJSON",
        f'echo "[cell {i}] checkpoint={c["checkpoint"]} ({kind}) start $(date +%T)"',
    ]
    for bench in c["benchmarks"]:
        argv = lm_eval_command(harness, bench, kind, path, f"${{RUN_DIR}}/{bench}")
        cmd = " ".join(a if a.startswith("${") else shlex.quote(a) for a in argv)
        lines += [
            f'{cmd} > "${{RUN_DIR}}/{bench}.log" 2>&1 '
            f'|| {{ echo "[cell {i}] {bench.upper()} FAILED"; exit 1; }}',
            f'echo "[cell {i}] {bench} done $(date +%T)"',
        ]
    lines.append(f'echo "[cell {i}] ALL BENCHMARKS OK $(date +%T)"')
    with open(f"{workdir}/cell_{i}.sh", "w") as f:
        f.write("\n".join(lines) + "\n")
print(f"generated {len(cells)} cell scripts in {workdir}")
PYEOF

NCELLS=$(ls "${WORKDIR}"/cell_*.sh 2>/dev/null | wc -l)
if [ "${NCELLS}" -eq 0 ]; then
    echo "ERROR: no cell scripts generated" >&2
    exit 1
fi
echo "Launching ${NCELLS} cells concurrently"

pids=()
for i in $(seq 0 $((NCELLS - 1))); do
    srun --overlap --ntasks=1 --cpus-per-task=64 \
         --environment=moralgym_verl \
         bash "${WORKDIR}/cell_${i}.sh" > "${WORKDIR}/cell_${i}.log" 2>&1 &
    pids+=($!)
done

failed=()
for i in "${!pids[@]}"; do
    if ! wait "${pids[$i]}"; then
        failed+=("$i")
    fi
done

echo
echo "=== per-cell output ==="
for i in $(seq 0 $((NCELLS - 1))); do
    echo "--- cell ${i} ---"
    cat "${WORKDIR}/cell_${i}.log"
done

# Long-term copy of whole cell dirs (scripts/slurm/cluster.env).
if [ -n "${STORE_BASE:-}" ]; then
    /usr/bin/python3.11 - "${BATCH_JSON}" "${PROJECT_ROOT}" "${SLURM_JOB_ID}" "${STORE_BASE}" <<'PYEOF'
import json, os, shutil, sys
batch_path, root, job_id, store = sys.argv[1:5]
for c in json.load(open(batch_path))["cells"]:
    rel = f"eval_results/{c['results_dir']}/{c['eval_group']}/cells"
    src = f"{root}/{rel}/{c['run_dir_stem']}_{job_id}"
    if not os.path.isdir(src):
        continue
    os.makedirs(f"{store}/{rel}", exist_ok=True)
    shutil.copytree(src, f"{store}/{rel}/{os.path.basename(src)}", dirs_exist_ok=True)
    print(f"staged {os.path.basename(src)}")
PYEOF
fi

echo
echo "Finished: $(date)"
if [ "${#failed[@]}" -gt 0 ]; then
    echo "FAILED cells: ${failed[*]} (scripts + logs in ${WORKDIR})"
    exit 1
fi
echo "All ${NCELLS} cells OK"
